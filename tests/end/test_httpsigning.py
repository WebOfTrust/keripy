# RFC 9421 Appendix B.1.4, test-key-ed25519, JWK form.
B14_D = "n4Ni-HpISpVObnQMW0wOhCKROaIKqKtW_2ZYb2p9KcU"
B14_X = "JrQLj5P_89iXES9-vFgrIy29clF9CC_oPPsw3c5D0bs"


def b64url(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def b14Signer():
    signer = Signer(raw=b64url(B14_D), code=MtrDex.Ed25519_Seed,
                    transferable=False)
    assert signer.verfer.raw == b64url(B14_X)
    return signer


# RFC 9421 Appendix B.2, test-request.
B2_REQUEST_HEADERS = [
    ("Host", "example.com"),
    ("Date", "Tue, 20 Apr 2021 02:07:55 GMT"),
    ("Content-Type", "application/json"),
    ("Content-Digest", "sha-512=:WZDPaVn/7XgHaAy8pmojAkGWoRx2UFChF41A2svX+T"
                       "aPm+AbwAgBWnrIiYllu7BNNyealdVLvRwEmTHWXvJwew==:"),
    ("Content-Length", "18"),
]
B2_REQUEST_BODY = b'{"hello": "world"}'

B26_BASE = (
    '"date": Tue, 20 Apr 2021 02:07:55 GMT\n'
    '"@method": POST\n'
    '"@path": /foo\n'
    '"@authority": example.com\n'
    '"content-type": application/json\n'
    '"content-length": 18\n'
    '"@signature-params": ("date" "@method" "@path" "@authority" '
    '"content-type" "content-length");created=1618884473'
    ';keyid="test-key-ed25519"'
)
B26_SIGNATURE = ("wqcAqbmYJ2ji2glfAMaRy4gruYYnx2nEFN2HN6jrnDnQCK1"
                 "u02Gb04v9EDgwUPiu4A0w6vuQv5lIp5WPpBKRCw==")


def test_content_digest_rfc9530():
    """RFC 9530 Appendix B and RFC 9421 Appendix B.2 digests."""
    # RFC 9530 Figure 12: {"hello": "world"} followed by LF.
    assert hs.contentDigest(b'{"hello": "world"}\n') == \
        "sha-256=:RK/0qy18MlBSVnWgjwz6lZEWjP/lF5HF9bvEF8FabDg=:"
    # RFC 9530 Figure 14: empty content.
    assert hs.contentDigest(b"") == \
        "sha-256=:47DEQpj8HBSa+/TImW+5JCeuQeRkm5NMpJWZG3hSuFU=:"
    # RFC 9421 Appendix B.2 test-request, sha-512.
    assert hs.contentDigest(B2_REQUEST_BODY, alg="sha-512") == \
        B2_REQUEST_HEADERS[3][1]
    # str bodies are UTF-8 encoded
    assert hs.contentDigest('{"hello": "world"}', alg="sha-512") == \
        B2_REQUEST_HEADERS[3][1]
    with pytest.raises(ValueError):
        hs.contentDigest(b"", alg="md5")


def test_verify_content_digest():
    body = B2_REQUEST_BODY
    sha256 = hs.contentDigest(body)
    sha512 = hs.contentDigest(body, alg="sha-512")

    hs.verifyContentDigest(sha256, body)
    hs.verifyContentDigest(sha512, body)
    hs.verifyContentDigest(f"{sha256}, {sha512}", body)
    # unknown algorithms are ignored (RFC 9530 section 2)
    hs.verifyContentDigest(f"md5=:AAAA:, {sha256}", body)
    hs.verifyContentDigest(f"unixsum=?1, {sha256}", body)

    with pytest.raises(hs.DigestMismatch) as ex:
        hs.verifyContentDigest(sha256, body + b" ")
    assert ex.value.code == "digest-mismatch"
    # every recognized member must match, not just one
    bad512 = hs.contentDigest(b"other", alg="sha-512")
    with pytest.raises(hs.DigestMismatch):
        hs.verifyContentDigest(f"{sha256}, {bad512}", body)

    for value in ("", "not a dictionary!", "sha-256=abc", "md5=:AAAA:",
                  'sha-256="text"', "sha-256=:AAAA", "sha-256=(:AAAA:)"):
        with pytest.raises(hs.MalformedDigest) as ex:
            hs.verifyContentDigest(value, body)
        assert ex.value.code == "malformed-digest"


def test_error_codes():
    """Every section 9 code, plus unauthenticated, has exactly one class."""
    codes = {
        "missing-signature": hs.MissingSignature,
        "missing-signature-input": hs.MissingSignatureInput,
        "malformed-signature": hs.MalformedSignature,
        "malformed-signature-input": hs.MalformedSignatureInput,
        "malformed-signature-label": hs.MalformedSignatureLabel,
        "missing-signature-label": hs.MissingSignatureLabel,
        "malformed-signature-value": hs.MalformedSignatureValue,
        "mode-mismatch": hs.ModeMismatch,
        "duplicate-component": hs.DuplicateComponent,
        "unsupported-component": hs.UnsupportedComponent,
        "insufficient-coverage": hs.InsufficientCoverage,
        "malformed-key": hs.MalformedKey,
        "unknown-key": hs.UnknownKey,
        "unsupported-signer": hs.UnsupportedSigner,
        "unsupported-algorithm": hs.UnsupportedAlgorithm,
        "missing-component": hs.MissingComponent,
        "signature-mismatch": hs.SignatureMismatch,
        "signature-stale": hs.SignatureStale,
        "signature-expired": hs.SignatureExpired,
        "malformed-digest": hs.MalformedDigest,
        "digest-mismatch": hs.DigestMismatch,
        "uncovered-body": hs.UncoveredBody,
        "unauthenticated": hs.Unauthenticated,
    }
    from keri import kering
    for code, klas in codes.items():
        assert klas.code == code
        assert issubclass(klas, hs.HttpSigError)
        err = klas("boom")
        assert err.code == code
        assert isinstance(err, kering.AuthNError)
        assert isinstance(err, kering.KeriError)
    assert hs.errorForCode("signature-stale") is hs.SignatureStale
    assert hs.errorForCode("no-such-code") is None


def test_signature_base_rfc_b26():
    """RFC 9421 Appendix B.2.6 base and signature, byte for byte."""
    params = hs.signatureParams(created=1618884473, keyid="test-key-ed25519")
    assert list(params) == ["created", "keyid"]
    base = hs.signatureBase(
        ["date", "@method", "@path", "@authority", "content-type",
         "content-length"],
        params,
        method="POST", authority="example.com", path="/foo",
        query="param=Value&Pet=dog", headers=B2_REQUEST_HEADERS)
    assert base == B26_BASE

    signer = b14Signer()
    cigar = signer.sign(base.encode("utf-8"))
    assert base64.b64encode(cigar.raw).decode() == B26_SIGNATURE
    assert signer.verfer.verify(sig=base64.b64decode(B26_SIGNATURE),
                                ser=B26_BASE.encode())

    # Plain field names from a local caller are lowercased; @authority falls
    # back to Host when no authority is supplied.
    assert hs.signatureBase(
        ["Date", "@method", "@path", "@authority", "Content-Type",
         "Content-Length"],
        params, method="POST", path="/foo",
        headers=dict(B2_REQUEST_HEADERS)) == B26_BASE


def test_signature_params_order():
    params = hs.signatureParams(tag="t", keyid="k", alg="ed25519", nonce="n",
                                expires=2, created=1)
    assert list(params) == ["created", "expires", "nonce", "alg", "keyid",
                            "tag"]
    # a verifier reserializes in the order received, not in emit order
    base = hs.signatureBase(["@method"], {"keyid": "k", "created": 1},
                            method="GET")
    assert base == ('"@method": GET\n'
                    '"@signature-params": ("@method");keyid="k";created=1')


def test_signature_base_rfc_2_4_reqres():
    """RFC 9421 section 2.4 response base binding request components."""
    request = hs.Requestage(method="POST", authority="example.com",
                            path="/foo", query="param=Value&Pet=dog",
                            headers=B2_REQUEST_HEADERS, body=B2_REQUEST_BODY)
    headers = [
        ("Date", "Tue, 20 Apr 2021 02:07:56 GMT"),
        ("Content-Type", "application/json"),
        ("Content-Length", "62"),
        ("Content-Digest", "sha-512=:0Y6iCBzGg5rZtoXS95Ijz03mslf6KAMCloESHObfwn"
                           "HJDbkkWWQz6PhhU9kxsTbARtY2PTBOzq24uJFpHsMuAg==:"),
    ]
    body = b'{"busy": true, "message": "Your call is very important to us"}'
    assert hs.contentDigest(body, alg="sha-512") == headers[3][1]

    base = hs.signatureBase(
        ['"@status"', '"content-digest"', '"content-type"',
         '"@authority";req', '"@method";req', '"@path";req',
         '"content-digest";req'],
        {"created": 1618884479, "keyid": "test-key-ecc-p256"},
        status=503, headers=headers, request=request)
    assert base == (
        '"@status": 503\n'
        '"content-digest": sha-512=:0Y6iCBzGg5rZtoXS95Ijz03mslf6KAMCloESHObf'
        'wnHJDbkkWWQz6PhhU9kxsTbARtY2PTBOzq24uJFpHsMuAg==:\n'
        '"content-type": application/json\n'
        '"@authority";req: example.com\n'
        '"@method";req: POST\n'
        '"@path";req: /foo\n'
        '"content-digest";req: sha-512=:WZDPaVn/7XgHaAy8pmojAkGWoRx2UFChF41A'
        '2svX+TaPm+AbwAgBWnrIiYllu7BNNyealdVLvRwEmTHWXvJwew==:\n'
        '"@signature-params": ("@status" "content-digest" "content-type" '
        '"@authority";req "@method";req "@path";req "content-digest";req)'
        ';created=1618884479;keyid="test-key-ecc-p256"')

    # the second section 2.4 example adds @query;req and request fields
    base = hs.signatureBase(
        ['"@status"', '"@query";req', '"content-length";req'],
        {"created": 1618884479, "keyid": "test-key-ecc-p256"},
        status=503, headers=headers, request=request)
    assert base == (
        '"@status": 503\n'
        '"@query";req: ?param=Value&Pet=dog\n'
        '"content-length";req: 18\n'
        '"@signature-params": ("@status" "@query";req "content-length";req)'
        ';created=1618884479;keyid="test-key-ecc-p256"')


def test_signature_base_rfc_2_1_fields():
    """RFC 9421 section 2.1 field value canonicalization examples."""
    headers = [
        ("Host", "www.example.com"),
        ("Date", "Tue, 20 Apr 2021 02:07:56 GMT"),
        ("X-OWS-Header", "   Leading and trailing whitespace.   "),
        ("X-Obs-Fold-Header", "Obsolete\r\n    line folding."),
        ("Cache-Control", "max-age=60"),
        ("Cache-Control", "   must-revalidate"),
        ("Example-Dict", " a=1,    b=2;x=1;y=2,   c=(a   b   c)"),
        ("X-Empty-Header", ""),
    ]
    base = hs.signatureBase(
        ["host", "date", "x-ows-header", "x-obs-fold-header", "cache-control",
         "example-dict", "x-empty-header"], {}, headers=headers)
    assert base.split("\n")[:-1] == [
        '"host": www.example.com',
        '"date": Tue, 20 Apr 2021 02:07:56 GMT',
        '"x-ows-header": Leading and trailing whitespace.',
        '"x-obs-fold-header": Obsolete line folding.',
        '"cache-control": max-age=60, must-revalidate',
        '"example-dict": a=1,    b=2;x=1;y=2,   c=(a   b   c)',
        '"x-empty-header": ',
    ]
    # a list value is separate field lines too, and a mapping works
    assert hs.signatureBase(
        ["cache-control"], {},
        headers={"Cache-Control": ["max-age=60", "must-revalidate"]}
    ).split("\n")[0] == '"cache-control": max-age=60, must-revalidate'


def test_signature_base_derived():
    """@method case, @path, @query, @authority, @status."""
    def line(component, **kwa):
        return hs.signatureBase([component], {}, **kwa).split("\n")[0]

    # RFC 9421 section 2.2.1: no case transformation of the method
    assert line("@method", method="post") == '"@method": post'
    assert line("@path", path="") == '"@path": /'
    assert line("@path", path="/a:b/%7E/x%2fy") == '"@path": /a:b/%7E/x%2fy'
    assert line("@query", query=None) == '"@query": ?'
    assert line("@query", query="") == '"@query": ?'
    assert line("@query", query="param=value&foo=bar&baz=bat%2Dman") == \
        '"@query": ?param=value&foo=bar&baz=bat%2Dman'
    assert line("@authority", authority="WWW.Example.COM") == \
        '"@authority": www.example.com'
    assert line("@authority", headers={"host": "Example.com:8080"}) == \
        '"@authority": example.com:8080'
    assert line("@status", status=200) == '"@status": 200'


def test_signature_base_refusals():
    def base(covered, **kwa):
        kwa.setdefault("method", "GET")
        kwa.setdefault("path", "/")
        kwa.setdefault("headers", {"host": "example.com", "x": "1"})
        return hs.signatureBase(covered, {}, **kwa)

    for component in ("@target-uri", "@scheme", "@request-target",
                      "@query-param", "@signature-params", "@nope"):
        with pytest.raises(hs.UnsupportedComponent) as ex:
            base([component])
        assert component in str(ex.value)
    for component in ('"x";sf', '"x";key="a"', '"x";bs', '"x";tr',
                      '"@query-param";name="a"'):
        with pytest.raises(hs.UnsupportedComponent):
            base([component])
    # req only in a response
    with pytest.raises(hs.UnsupportedComponent):
        base(['"@method";req'])
    # @status only in a response, and never with req
    with pytest.raises(hs.UnsupportedComponent):
        base(["@status"])
    request = hs.Requestage(method="GET", authority="a", path="/", query=None,
                            headers={}, body=b"")
    with pytest.raises(hs.UnsupportedComponent):
        base(['"@status";req'], status=200, request=request)
    # request-targeted derived components need req on a response
    with pytest.raises(hs.UnsupportedComponent):
        base(["@method"], status=200, request=request)
    # an uppercase name in serialized (wire) form is refused
    with pytest.raises(hs.MalformedSignatureInput):
        base(['"X"'])

    with pytest.raises(hs.DuplicateComponent):
        base(["@method", "@path", "@method"])
    with pytest.raises(hs.DuplicateComponent):
        base(["x", "X"])

    with pytest.raises(hs.MissingComponent) as ex:
        base(["content-digest"])
    assert "content-digest" in str(ex.value)
    with pytest.raises(hs.MissingComponent):
        base(["@authority"], headers={})


def test_signature_base_duplicates_ignore_param_order():
    """Duplicate detection ignores parameter order and runs before the
    unsupported-component check (profile section 9)."""
    request = hs.Requestage(method="GET", authority="a", path="/", query=None,
                            headers={"x": "1"}, body=b"")
    with pytest.raises(hs.DuplicateComponent):
        hs.signatureBase(['"x";req;bs', '"x";bs;req'], {}, status=200,
                         headers={}, request=request)
    # the same name with and without req is not a duplicate (section 2.4)
    base = hs.signatureBase(["@status", "x", '"x";req'], {}, status=200,
                            headers={"x": "2"}, request=request)
    assert base.split("\n")[1:3] == ['"x": 2', '"x";req: 1']


# Sign and verify. A fixed clock keeps signatures reproducible.

NOW = 1618884473
SEED = b"\x01" * 32


def ntSigner(seed=SEED):
    """Non-transferable Ed25519 signer; its verfer qb64 is its own AID."""
    return Signer(raw=seed, code=MtrDex.Ed25519_Seed, transferable=False)


def request(**kwa):
    """Keyword arguments of a canonical test request."""
    msg = dict(method="POST", authority="keria.example",
               path="/identifiers/aid1/events", query="type=rot",
               headers={"Content-Type": "application/json",
                        "Content-Length": "7"},
               body=b'{"a":1}')
    msg.update(kwa)
    return msg


def signed(signer=None, *, sign=None, **kwa):
    """Returns request kwargs with the signature headers added."""
    msg = request(**kwa)
    signer = signer if signer is not None else ntSigner()
    sign = {**dict(created=NOW, nonce="n1"), **(sign or {})}
    added = hs.signRequest(signer=signer, **msg, **sign)
    msg["headers"] = {**msg["headers"], **added}
    return msg


def verify(msg, **kwa):
    kwa.setdefault("resolver", hs.keverResolver({}))
    kwa.setdefault("now", NOW)
    return hs.verifyRequest(**msg, **kwa)


def test_sign_request_headers():
    signer = ntSigner()
    msg = request()
    added = hs.signRequest(signer=signer, created=NOW, nonce="n1", **msg)
    assert list(added) == ["Content-Digest", "Signature-Input", "Signature"]
    assert added["Content-Digest"] == hs.contentDigest(b'{"a":1}')
    assert added["Signature-Input"] == (
        'signify=("@method" "@authority" "@path" "@query" "content-digest")'
        f';created={NOW};nonce="n1";alg="ed25519";keyid="{signer.verfer.qb64}"')
    base = hs.signatureBase(
        ["@method", "@authority", "@path", "@query", "content-digest"],
        hs.signatureParams(created=NOW, nonce="n1", alg="ed25519",
                           keyid=signer.verfer.qb64),
        method="POST", authority="keria.example",
        path="/identifiers/aid1/events", query="type=rot",
        headers={**msg["headers"], **added})
    sig = signer.sign(base.encode()).raw
    assert added["Signature"] == \
        f"signify=:{base64.b64encode(sig).decode()}:"

    # no body: no content-digest, not covered
    added = hs.signRequest(signer=signer, created=NOW, nonce=False, alg=None,
                           tag="t", label="sig1", expires=NOW + 10,
                           **request(method="GET", body=None, headers={}))
    assert list(added) == ["Signature-Input", "Signature"]
    assert added["Signature-Input"] == (
        'sig1=("@method" "@authority" "@path" "@query")'
        f';created={NOW};expires={NOW + 10};keyid="{signer.verfer.qb64}"'
        ';tag="t"')


