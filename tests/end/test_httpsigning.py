# RFC 9421 Appendix B.1.4, test-key-ed25519, JWK form.
B14_D = "n4Ni-HpISpVObnQMW0wOhCKROaIKqKtW_2ZYb2p9KcU"
B14_X = "JrQLj5P_89iXES9-vFgrIy29clF9CC_oPPsw3c5D0bs"


def b64url(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def b14Signer():
    signer = Signer(raw=b64url(B14_D), code=MtrDex.Ed25519_Seed,
                    transferable=False)
    assert signer.verfer.raw == b64url(B14_X)
    return signer


