    with pytest.raises(hs.UnknownKey):
        verifyResp(rep, kept, keyid=ntSigner().verfer.qb64)
    # freshness applies to responses too
    with pytest.raises(hs.SignatureStale):
        verifyResp(rep, kept, now=NOW + 1000)


