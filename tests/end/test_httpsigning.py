def test_kever_resolver():
    with habbing.openHab(name="ctrl", salt=b"0123456789abcdef",
                         temp=True) as (hby, hab):
        multi = hby.makeHab(name="multi", icount=2, isith="2", ncount=2,
                            nsith="2")
        one = hby.makeHab(name="one", icount=2, isith="1", ncount=2,
                          nsith="1")
        resolve = hs.keverResolver(hby.kevers)

        assert resolve(hab.pre).qb64 == hab.kever.verfers[0].qb64
        nt = ntSigner()
        assert resolve(nt.verfer.qb64).qb64 == nt.verfer.qb64

        for keyid in ("", "notanaid", hab.pre + "A", hab.pre[:-1],
                      nt.sign(b"x").qb64):
            with pytest.raises(hs.MalformedKey) as ex:
                resolve(keyid)
            assert ex.value.code == "malformed-key"

        # a transferable prefix the verifier holds no KEL for
        with pytest.raises(hs.UnknownKey):
            resolve("E" + hab.pre[1:-1] + ("A" if hab.pre[-1] != "A" else "B"))
        # basic transferable D prefix is never treated as a raw key (R1)
        dkey = Signer(raw=SEED, transferable=True).verfer.qb64
        assert dkey.startswith("D")
        with pytest.raises(hs.UnknownKey) as ex:
            resolve(dkey)
        assert ex.value.code == "unknown-key"

        for other in (multi, one):
            with pytest.raises(hs.UnsupportedSigner) as ex:
                resolve(other.pre)
            assert ex.value.code == "unsupported-signer"


def test_kever_resolver_after_reopen(tmp_path):
    """Key state in the database but not yet cached in memory, as after a
    restart, still resolves (Baser.kevers reads through on in and [] but not
    on get)."""
    from keri.core import eventing, parsing
    with habbing.openHab(name="ctrl", salt=b"0123456789abcdef",
                         temp=True) as (chby, ctrl):
        icp = ctrl.msgOwnInception()
        hby = habbing.Habery(name="verifier", temp=False,
                             headDirPath=str(tmp_path))
        try:
            hby.makeHab(name="agent")
            kvy = eventing.Kevery(db=hby.db, lax=True, local=False)
            parsing.Parser().parse(ims=bytearray(icp), kvy=kvy)
        finally:
            hby.close()

        hby = habbing.Habery(name="verifier", temp=False,
                             headDirPath=str(tmp_path))
        try:
            assert not dict.__contains__(hby.kevers, ctrl.pre)  # not cached
            verfer = hs.keverResolver(hby.kevers)(ctrl.pre)
            assert verfer.qb64 == ctrl.kever.verfers[0].qb64
        finally:
            hby.close(clear=True)


def test_effective_signer():
    """Profile R4 (draft 6): the key state qualifies when exactly one current
    key satisfies the signing threshold alone, and that key is used."""
    a, b, c = (ntSigner(bytes([i]) * 32).verfer for i in (7, 8, 9))

    def aid(name):
        return Diger(ser=name.encode()).qb64

    def kever(verfers, sith):
        return SimpleNamespace(verfers=verfers, tholder=Tholder(sith=sith))

    kevers = {
        # Signify after a passcode rotation: keys [new, prior-next]
        aid("PasscodeRotated"): kever([a, b], ["1", "0"]),
        aid("SecondKeyOnly"): kever([a, b], ["0", "1"]),
        aid("Plain"): kever([a], "1"),
        aid("EitherKey"): kever([a, b], "1"),
        aid("TwoOfThree"): kever([a, b, c], "2"),
        aid("Halves"): kever([a, b], ["1/2", "1/2"]),
        aid("BothWhole"): kever([a, b], ["1", "1"]),
    }
    resolve = hs.keverResolver(kevers)
    assert resolve(aid("PasscodeRotated")).qb64 == a.qb64
    assert resolve(aid("SecondKeyOnly")).qb64 == b.qb64
    assert resolve(aid("Plain")).qb64 == a.qb64
    for pre in (aid("EitherKey"),
                aid("TwoOfThree"),
                aid("Halves"),
                aid("BothWhole")):
        with pytest.raises(hs.UnsupportedSigner):
            resolve(pre)

    # a real habitat in the passcode-rotated shape signs and verifies
    with habbing.openHab(name="ctrl", salt=b"0123456789abcdef",
                         temp=True) as (hby, hab):
        rotated = hby.makeHab(name="rotated", icount=2, isith=["1", "0"],
                              ncount=2, nsith=["1", "0"])
        msg = request()
        added = hs.signRequest(hab=rotated, created=NOW, nonce="n1", **msg)
        msg["headers"] = {**msg["headers"], **added}
        verified = verify(msg, resolver=hs.keverResolver(hby.kevers))
        assert verified.verfer.qb64 == rotated.kever.verfers[0].qb64


